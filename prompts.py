def render(template: str, **kwargs) -> str:
    """安全替换 {key} 占位符（不做正则/下标/属性解析）。"""
    out = template
    for k, v in kwargs.items():
        out = out.replace("{" + k + "}", "" if v is None else str(v))
    return out


